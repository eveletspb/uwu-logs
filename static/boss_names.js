// The first spelling is used for combat logs that contain an already localized name.
const ENGLISH_BOSSES = new Map();
for (const [english, russian] of Object.entries(RUSSIAN_BOSSES)) {
  if (!ENGLISH_BOSSES.has(russian)) ENGLISH_BOSSES.set(russian, english);
}

export function bossName(name, language = globalThis.navigator?.language) {
  const mode = / \((?:10|25)[NH]\)$/.exec(name)?.[0] ?? "";
  const key = mode ? name.slice(0, -mode.length) : name;
  const translated = /^ru(?:[-_]|$)/i.test(language)
    ? (Object.hasOwn(RUSSIAN_BOSSES, key) ? RUSSIAN_BOSSES[key] : undefined)
    : ENGLISH_BOSSES.get(key);
  // shortcut: display the log name for encounters outside the translation catalog.
  return translated ? translated + mode : name;
}

export function localizeBossLabels() {
  for (const element of document.querySelectorAll("[data-boss-label]")) {
    element.textContent = bossName(element.textContent);
  }
  for (const element of document.querySelectorAll("[data-boss-title]")) {
    element.title = element.title.split(" · ").map(name => bossName(name)).join(" · ");
  }
}
